 operation text NOT NULL CHECK(operation IN ('train','compare','evaluate')),
 candidate_id text, status text NOT NULL CHECK(status IN ('queued','running','complete','insufficient_labels','failed','cancelled','interrupted')),
 created bigint NOT NULL, started bigint, finished bigint, report jsonb, model_sha256 text
);
CREATE INDEX quality_job_queue ON noisefence.quality_jobs(status,created);
CREATE TABLE noisefence.quality_worker_status (
 id integer PRIMARY KEY CHECK(id=1), heartbeat bigint NOT NULL, build text NOT NULL
);
CREATE TABLE noisefence.quality_exposure_state (
 id integer PRIMARY KEY CHECK(id=1), tracking_since bigint NOT NULL, generation bigint NOT NULL DEFAULT 0
);
INSERT INTO noisefence.quality_exposure_state(id,tracking_since) VALUES(1,EXTRACT(EPOCH FROM CURRENT_TIMESTAMP)::bigint);
CREATE TABLE noisefence.quality_export_batches (batch_id text PRIMARY KEY,exposed_at bigint NOT NULL);
CREATE TABLE noisefence.quality_export_campaigns (
 fingerprint text NOT NULL,simhash text NOT NULL,exposed_at bigint NOT NULL,PRIMARY KEY(fingerprint,simhash)
);
CREATE TABLE noisefence.queue_commands (
 id text PRIMARY KEY, node text NOT NULL REFERENCES noisefence.sources,
 node_epoch text NOT NULL,
 message_id text NOT NULL, recipient text NOT NULL, command text NOT NULL CHECK(command IN ('release','delete','retry')),
 username text NOT NULL, session_hash text NOT NULL CHECK(length(session_hash)=64), actor_version bigint NOT NULL,
 created bigint NOT NULL, expires bigint NOT NULL,
 result text, finished bigint, execution_result text, executed_at bigint
);
CREATE UNIQUE INDEX pending_queue_command ON noisefence.queue_commands(node,message_id,recipient) WHERE finished IS NULL;
CREATE TABLE noisefence.command_tombstones (
 id text PRIMARY KEY, node text NOT NULL, epoch text NOT NULL,
 execution_result text, executed_at bigint,
 FOREIGN KEY(node,epoch) REFERENCES noisefence.sources(node,epoch)
);
CREATE TABLE noisefence.migration_state (
 id integer PRIMARY KEY CHECK(id=1), source_digest text NOT NULL,
 imported_at bigint NOT NULL, activated_at bigint, report jsonb NOT NULL
);

